/** Colores semánticos que M3 no expone (éxito, advertencia, rating). */
@Immutable
data class TheHouseExtraColors(
    val success: Color,
    val onSuccess: Color,
    val successContainer: Color,
    val onSuccessContainer: Color,
    val warning: Color,
    val onWarning: Color,
    val warningContainer: Color,
    val onWarningContainer: Color,
    val rating: Color,
)

private val LightExtraColors = TheHouseExtraColors(
    success = Success,
    onSuccess = OnSuccess,
    successContainer = SuccessContainer,
    onSuccessContainer = OnSuccessContainer,
    warning = Warning,
    onWarning = OnWarning,
    warningContainer = WarningContainer,
    onWarningContainer = OnWarningContainer,
    rating = Rating,
)

private val DarkExtraColors = TheHouseExtraColors(
    success = SuccessDark,
    onSuccess = OnSuccessDark,
    successContainer = SuccessContainerDark,
    onSuccessContainer = OnSuccessContainerDark,
    warning = WarningDark,
    onWarning = OnWarningDark,
    warningContainer = WarningContainerDark,
    onWarningContainer = OnWarningContainerDark,
    rating = RatingDark,
)

val LocalTheHouseExtraColors = staticCompositionLocalOf { LightExtraColors }

/** Acceso a los colores extendidos: `MaterialTheme.theHouseColors.success`. */
val MaterialTheme.theHouseColors: TheHouseExtraColors
    @Composable
    @ReadOnlyComposable
    get() = LocalTheHouseExtraColors.current

/** Radios del prototipo: chips/dots full, cards 16dp, contenedores 28dp. */
private val TheHouseShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(20.dp),
    extraLarge = RoundedCornerShape(28.dp),
)

@Composable
fun TheHouseTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val extraColors = if (darkTheme) DarkExtraColors else LightExtraColors

    CompositionLocalProvider(LocalTheHouseExtraColors provides extraColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = TheHouseShapes,
            content = content,
        )
    }
}
